QByteArray encryptEcbHexUpper(const QByteArray &plain, const QByteArray &key)
{
    if (key.size() < 16) return QByteArray();
    quint8 w[176];
    quint8 k[16];
    std::memcpy(k, key.constData(), 16);
    expandKey(k, w);

    const int pad = 16 - (plain.size() % 16);
    QByteArray padded = plain;
    padded.append(QByteArray(pad, static_cast<char>(pad)));

    static const char *hex = "0123456789ABCDEF";
    QByteArray out;
    out.reserve(padded.size() * 2);
    for (int i = 0; i < padded.size(); i += 16) {
        quint8 block[16], cipher[16];
        std::memcpy(block, padded.constData() + i, 16);
        encryptBlock(block, cipher, w);
        for (int j = 0; j < 16; ++j) {
            out.append(hex[cipher[j] >> 4]);
            out.append(hex[cipher[j] & 0x0f]);
        }
    }
    return out;
}

QByteArray linuxapiForm(const QJsonObject &payload)
{
    // key 与洛雪 wy/utils/crypto.js 的 linuxapiKey 完全一致
    const QByteArray key = QByteArrayLiteral("rFgB&h#%2?^eDg:Q");
    const QByteArray text = QJsonDocument(payload).toJson(QJsonDocument::Compact);
    QUrlQuery q;
    q.addQueryItem(QStringLiteral("eparams"),
                   QString::fromLatin1(encryptEcbHexUpper(text, key)));
    return q.toString(QUrl::FullyEncoded).toUtf8();
}

bool selfTest()
{
    // FIPS-197 Appendix C.1 AES-128 标准向量
    const QByteArray key = QByteArray::fromHex("000102030405060708090a0b0c0d0e0f");
    const QByteArray plain = QByteArray::fromHex("00112233445566778899aabbccddeeff");
    const QByteArray got = encryptEcbHexUpper(plain, key);
    // 单块会被 PKCS7 补一整个块，取前 32 个 hex 字符比对
    return got.left(32) == QByteArrayLiteral("69C4E0D86A7B0430D8CDB78070B4C55A");
}

