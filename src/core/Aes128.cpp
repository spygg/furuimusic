const quint8 kRcon[11] = {0x00,0x01,0x02,0x04,0x08,0x10,0x20,0x40,0x80,0x1b,0x36};

inline quint8 xtime(quint8 x)
{
    return static_cast<quint8>((x << 1) ^ ((x & 0x80) ? 0x1b : 0x00));
}

void expandKey(const quint8 key[16], quint8 w[176])
{
    std::memcpy(w, key, 16);
    for (int i = 4; i < 44; ++i) {
        quint8 t[4];
        std::memcpy(t, w + 4 * (i - 1), 4);
        if (i % 4 == 0) {
            const quint8 tmp = t[0];
            t[0] = kSBox[t[1]] ^ kRcon[i / 4];
            t[1] = kSBox[t[2]];
            t[2] = kSBox[t[3]];
            t[3] = kSBox[tmp];
        }
        for (int j = 0; j < 4; ++j)
            w[4 * i + j] = w[4 * (i - 4) + j] ^ t[j];
    }
}

void addRoundKey(quint8 s[16], const quint8 *roundKey)
{
    for (int i = 0; i < 16; ++i) s[i] ^= roundKey[i];
}

void subBytes(quint8 s[16])
{
    for (int i = 0; i < 16; ++i) s[i] = kSBox[s[i]];
}

void shiftRows(quint8 s[16])
{
    quint8 t;
    // 状态矩阵按列存储：s[r + 4*c]
    t = s[1]; s[1] = s[5]; s[5] = s[9]; s[9] = s[13]; s[13] = t;
    t = s[2]; s[2] = s[10]; s[10] = t;
    t = s[6]; s[6] = s[14]; s[14] = t;
    t = s[15]; s[15] = s[11]; s[11] = s[7]; s[7] = s[3]; s[3] = t;
}

void mixColumns(quint8 s[16])
{
    for (int c = 0; c < 4; ++c) {
        quint8 *p = s + 4 * c;
        const quint8 a0 = p[0], a1 = p[1], a2 = p[2], a3 = p[3];
        const quint8 all = a0 ^ a1 ^ a2 ^ a3;
        p[0] = a0 ^ all ^ xtime(a0 ^ a1);
        p[1] = a1 ^ all ^ xtime(a1 ^ a2);
        p[2] = a2 ^ all ^ xtime(a2 ^ a3);
        p[3] = a3 ^ all ^ xtime(a3 ^ a0);
    }
}

void encryptBlock(const quint8 in[16], quint8 out[16], const quint8 w[176])
{
    quint8 s[16];
    std::memcpy(s, in, 16);
    addRoundKey(s, w);
    for (int round = 1; round <= 9; ++round) {
        subBytes(s);
        shiftRows(s);
        mixColumns(s);
        addRoundKey(s, w + 16 * round);
    }
    subBytes(s);
    shiftRows(s);
    addRoundKey(s, w + 160);
    std::memcpy(out, s, 16);
}

